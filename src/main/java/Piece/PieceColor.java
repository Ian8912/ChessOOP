package Piece;

/**
 * Represents the two possible colors of a chess piece: white or black.
 *
 * <p>This enum is used to distinguish between opposing players
 * and determine piece behavior such as turn order and sprite rendering.</p>
 *
 * @see Piece
 */
public enum PieceColor {
    /** The white color used for one side's pieces. */
    WHITE,

    /** The black color used for the opposing side's pieces. */
    BLACK
}